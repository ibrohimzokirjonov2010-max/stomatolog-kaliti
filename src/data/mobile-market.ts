export function getMobileMarket(id: string) {
  return mobileMarketItems.find((item) => item.id === id) ?? null;
}

export function mobileMarketProduct(item: MobileMarketItem): Product {
  return {
    id: item.id,
    name: item.name,
    brand: item.brand,
    category: item.chip === "jihozlar" ? "jihozlar" : item.chip === "laboratoriya" ? "laboratoriya" : item.chip === "implantlar" ? "implantlar" : item.chip === "asboblar" ? "asboblar" : "materiallar",
    price: item.price,
    oldPrice: item.oldPrice,
    discount: item.discount,
    rating: item.rating,
    reviews: item.reviews,
    inStock: true,
    delivery: item.delivery,
    image: item.image,
    description: item.description,
  };
}
